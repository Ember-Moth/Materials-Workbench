//! Mock: built-in sample structures. They stand in for structures saved in
//! a project file (M6). Everything derived from them, the symmetry analysis
//! included, is real.
//!
//! Lattice parameters and coordinates are the commonly cited room-temperature
//! values.

use crate::{CellParams, Derived, Lattice, Site, SpaceGroup, Structure, SymOp, Symmetry};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum SampleKey {
    Rutile,
    RutileSupercell,
    StrontiumTitanate,
}

pub struct Sample {
    pub structure: Structure,
    pub derived: Derived,
}

pub fn load(key: SampleKey) -> Sample {
    match key {
        SampleKey::Rutile => rutile(),
        SampleKey::RutileSupercell => rutile_supercell(),
        SampleKey::StrontiumTitanate => strontium_titanate(),
    }
}

const RUTILE_A: f64 = 4.594;
const RUTILE_C: f64 = 2.959;
const RUTILE_X: f64 = 0.3048;

/// The group generated by operations written in CIF notation.
fn group(generators: &[&str]) -> Symmetry {
    let generators: Vec<SymOp> = generators
        .iter()
        .map(|g| SymOp::parse(g).expect("valid generator"))
        .collect();
    Symmetry::generate(&generators).expect("a space group")
}

fn space_group(hm_symbol: &str, it_number: u16) -> SpaceGroup {
    SpaceGroup::new(Some(hm_symbol.into()), Some(it_number))
}

fn rutile_structure() -> Structure {
    let lattice = Lattice::new(CellParams::new(
        RUTILE_A, RUTILE_A, RUTILE_C, 90.0, 90.0, 90.0,
    ));
    Structure::new(
        lattice,
        group(&["-y+1/2,x+1/2,z+1/2", "-x+1/2,y+1/2,-z+1/2", "-x,-y,-z"]),
        vec![
            Site::single(1, "Ti1", "Ti", [0.0, 0.0, 0.0]),
            Site::single(2, "O1", "O", [RUTILE_X, RUTILE_X, 0.0]),
        ],
    )
    .with_space_group(space_group("P 42/m n m", 136))
}

/// Rutile, TiO₂ in P4₂/mnm: Ti on 2a, O on 4f at x, x, 0.
fn rutile() -> Sample {
    let structure = rutile_structure();
    let derived = Derived::compute(&structure);
    Sample { structure, derived }
}

/// A 2 × 2 × 2 rutile supercell in P1: every atom is its own site.
fn rutile_supercell() -> Sample {
    let rutile = rutile_structure();
    let cell_contents: Vec<(String, [f64; 3])> = Derived::compute(&rutile)
        .orbits
        .iter()
        .flat_map(|orbit| {
            let element = rutile
                .site(orbit.site)
                .map_or_else(String::new, |site| site.element().to_string());
            orbit
                .positions
                .iter()
                .map(move |position| (element.clone(), *position))
        })
        .collect();
    let lattice = Lattice::new(CellParams::new(
        2.0 * RUTILE_A,
        2.0 * RUTILE_A,
        2.0 * RUTILE_C,
        90.0,
        90.0,
        90.0,
    ));
    let mut sites = Vec::new();
    let mut counts = [0u32; 2];
    for (i, j, k) in (0..2).flat_map(|i| (0..2).flat_map(move |j| (0..2).map(move |k| (i, j, k)))) {
        for (element, frac) in &cell_contents {
            let position = [
                (frac[0] + f64::from(i)) / 2.0,
                (frac[1] + f64::from(j)) / 2.0,
                (frac[2] + f64::from(k)) / 2.0,
            ];
            let count = &mut counts[usize::from(element == "O")];
            *count += 1;
            let id = sites.len() as u32 + 1;
            sites.push(Site::single(
                id,
                &format!("{element}{count}"),
                element,
                position,
            ));
        }
    }
    let structure =
        Structure::new(lattice, Symmetry::p1(), sites).with_space_group(space_group("P 1", 1));
    let derived = Derived::compute(&structure);
    Sample { structure, derived }
}

const SRTIO3_A: f64 = 3.905;

/// Cubic perovskite SrTiO₃ (Pm-3m, Sr 1a, Ti 1b, O 3c).
fn strontium_titanate() -> Sample {
    let lattice = Lattice::new(CellParams::new(
        SRTIO3_A, SRTIO3_A, SRTIO3_A, 90.0, 90.0, 90.0,
    ));
    let structure = Structure::new(
        lattice,
        group(&["-y,x,z", "z,x,y", "-x,-y,-z"]),
        vec![
            Site::single(1, "Sr1", "Sr", [0.0, 0.0, 0.0]),
            Site::single(2, "Ti1", "Ti", [0.5, 0.5, 0.5]),
            Site::single(3, "O1", "O", [0.0, 0.5, 0.5]),
        ],
    )
    .with_space_group(space_group("P m -3 m", 221));
    let derived = Derived::compute(&structure);
    Sample { structure, derived }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{CellParam, Constraint, CrystalSystem};

    const ALL: [SampleKey; 3] = [
        SampleKey::Rutile,
        SampleKey::RutileSupercell,
        SampleKey::StrontiumTitanate,
    ];

    #[test]
    fn rutile_shows_a_full_cell() {
        let sample = load(SampleKey::Rutile);
        assert_eq!(sample.structure.symmetry.operations().len(), 16);
        // 8 corner Ti + 1 body-center Ti + 4 O, two of them repeated at z = 1.
        assert_eq!(sample.derived.atoms.len(), 15);
        let density = sample.derived.density.expect("known elements");
        assert!((density - 4.25).abs() < 0.01, "{density}");
    }

    #[test]
    fn strontium_titanate_shows_a_full_cell() {
        let sample = load(SampleKey::StrontiumTitanate);
        assert_eq!(sample.structure.symmetry.operations().len(), 48);
        assert_eq!(sample.derived.atoms.len(), 8 + 1 + 6);
        let density = sample.derived.density.expect("known elements");
        assert!((density - 5.12).abs() < 0.01, "{density}");
    }

    #[test]
    fn supercell_is_p1_with_one_site_per_atom() {
        let sample = load(SampleKey::RutileSupercell);
        assert_eq!(sample.structure.sites.len(), 48);
        assert_eq!(sample.derived.atoms_in_cell(), 48);
        assert_eq!(sample.structure.edit_mode(), crate::EditMode::P1);
        let density = sample.derived.density.expect("known elements");
        assert!((density - 4.25).abs() < 0.01, "{density}");
    }

    fn wyckoffs(key: SampleKey) -> Vec<String> {
        let sample = load(key);
        sample
            .structure
            .sites
            .iter()
            .map(|site| {
                let symmetry = sample.derived.site_symmetry(site.id).expect("analyzed");
                format!(
                    "{} {}",
                    symmetry.wyckoff.as_ref().expect("tabulated"),
                    symmetry.form
                )
            })
            .collect()
    }

    #[test]
    fn symmetry_of_the_samples() {
        let rutile = load(SampleKey::Rutile);
        let analysis = &rutile.derived.symmetry;
        let space_group = analysis.space_group.as_ref().expect("identified");
        assert_eq!(
            (space_group.number, space_group.hm_symbol),
            (136, "P 4_2/m n m")
        );
        assert_eq!(analysis.crystal_system(), Some(CrystalSystem::Tetragonal));
        assert_eq!(
            analysis.cell.get(CellParam::B),
            Constraint::Equals(CellParam::A)
        );
        assert_eq!(analysis.cell.get(CellParam::C), Constraint::Free);
        assert!(analysis.detected.is_none());
        assert_eq!(wyckoffs(SampleKey::Rutile), ["2a 0, 0, 0", "4f x, x, 0"]);

        assert_eq!(
            wyckoffs(SampleKey::StrontiumTitanate),
            ["1a 0, 0, 0", "1b 1/2, 1/2, 1/2", "3c 0, 1/2, 1/2"]
        );
    }

    #[test]
    fn the_supercell_in_p1_is_detected_as_rutile() {
        let sample = load(SampleKey::RutileSupercell);
        let analysis = &sample.derived.symmetry;
        assert_eq!(analysis.space_group.as_ref().map(|s| s.number), Some(1));
        assert!(
            wyckoffs(SampleKey::RutileSupercell)
                .iter()
                .all(|w| w == "1a x, y, z")
        );
        let detected = analysis.detected.as_ref().expect("P1 is searched");
        assert_eq!((detected.number, detected.hm_symbol), (136, "P 4_2/m n m"));
        // The 2 × 2 × 2 cell holds 8 cells' worth of translations.
        assert_eq!(detected.operations, 16 * 8);
        let letters: std::collections::BTreeSet<char> =
            detected.wyckoffs.iter().map(|(_, w)| *w).collect();
        assert_eq!(letters, ['a', 'f'].into());
    }

    #[test]
    fn wyckoff_multiplicities_match_the_expansion() {
        for key in ALL {
            let sample = load(key);
            for site in &sample.structure.sites {
                let symmetry = sample.derived.site_symmetry(site.id).expect("analyzed");
                let operations = sample.structure.symmetry.operations().len();
                assert_eq!(
                    sample.derived.multiplicity(site.id),
                    Some(operations / symmetry.order),
                    "{key:?} {}",
                    site.label()
                );
            }
        }
    }

    #[test]
    fn every_display_atom_refers_to_a_site() {
        for key in ALL {
            let sample = load(key);
            for atom in &sample.derived.atoms {
                assert!(sample.structure.site(atom.atom.site).is_some(), "{key:?}");
            }
        }
    }
}
